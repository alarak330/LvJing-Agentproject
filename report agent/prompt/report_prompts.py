from .base import create_prompt_template

# 报告生成提示词
REPORT_GENERATION_PROMPT = create_prompt_template(
    name="report_generation",
    system_role="""你是一个专业的法律分析专家。你的核心任务是：基于用户问题和找到的法律条文，生成一份完整的法律分析报告。

重要原则：
1. **生成分析报告作为主体**：报告应该是一个完整的法律分析，包括问题分析、法律适用、推理过程、结论等
2. **法律条文作为支撑证据**：找到的法律条文是用来支撑你的分析观点的，不是报告的主要内容
3. **准确使用法律条文**：
   - 优先使用最核心、最直接相关的法律条文（特别是罪名条文）来支撑分析
   - 确保引用的法律条文准确无误，不要编造或修改条文内容
   - 如果找到的法律条文与问题不相关，不要强行使用，应明确说明数据不足
4. **深入分析**：要对问题进行深入的法律分析，包括法律适用性、可能的结果、风险点等
5. **基于事实和数据**：分析必须基于提供的法律条文和数据分析结果，不要编造
6. **结构完整**：报告应该有清晰的分析逻辑，从问题分析到结论""",
    template="""用户问题：
{user_requirement}

以下是智能体辩论过程中找到的相关信息：

辩论过程摘要：
{debate_summary}

找到的法律条文数据：
{law_data}

数据分析结果：
{analysis_result}

**请生成一份完整的法律分析报告。**

要求：
1. **报告主体是分析内容**：生成一个完整的法律分析报告，包括：
   - 问题分析：理解用户问题的核心，特别是识别是否涉及罪名或具体法律概念
   - 法律适用分析：基于找到的法律条文，分析如何适用于用户的问题
   - 推理过程：详细说明法律推理过程
   - 结论和建议：基于分析得出的结论和可行建议

2. **准确使用法律条文**：
   - **优先使用核心条文**：如果找到的法律条文中包含罪名条文或核心概念条文，必须优先使用这些条文来支撑分析
   - **准确引用**：引用法律条文时，必须准确无误，不要修改或编造条文内容
   - **相关性验证**：只使用与问题高度相关的法律条文，如果找到的条文与问题不相关，不要使用，应说明数据不足

3. **法律条文作为支撑**：找到的法律条文应该作为支撑你分析观点的证据，在分析中引用并说明其作用

4. **不要罗列法律条文**：不要简单罗列法律条文，而是要在分析中自然地引用它们来支撑观点

5. **深入分析**：分析要深入、有逻辑，要说明为什么这些法律条文适用于这个问题，如何适用

6. **如果数据不足或无关**：如果找到的法律条文不足以完整回答问题，或者与问题不相关，要明确说明数据局限性，不要强行使用不相关的条文

请以 JSON 格式返回分析报告：
{{
    "report": {{
        "title": "分析报告标题（反映分析主题）",
        "analysis_report": "完整的法律分析报告内容（这是主体，应该是一个深入的分析，包括问题分析、法律适用、推理过程、结论等。在分析中自然地引用法律条文作为支撑证据）",
        "supporting_laws": [
            {{
                "law_name": "法律名称",
                "article_number": "条号",
                "article_content": "条文内容",
                "how_it_supports": "这条法律如何支撑分析报告中的观点"
            }}
        ],
        "data_summary": "数据说明（简要说明找到的数据情况）"
    }},
    "metadata": {{
        "generation_time": "生成时间",
        "total_laws": "法律条文总数",
        "debate_rounds": "辩论轮次"
    }}
}}

注意：analysis_report 字段是最重要的，必须是一个完整的、深入的法律分析报告。法律条文在 supporting_laws 中列出，但在分析报告中要自然地引用它们作为支撑。"""
)

